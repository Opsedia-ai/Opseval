"""Generate the console's API types from the server's models.

    uv run python scripts/console_types.py          # write packages/console/src/lib/api.gen.ts
    uv run python scripts/console_types.py --check  # fail if it is out of date (CI)

``opseval.server.schemas`` is the one source of truth for the wire format. The console used
to mirror it by hand in ``types.ts``, which could drift without anyone noticing; now the
TypeScript is generated from the same models the API validates with, and ``make check`` fails
when the two disagree, as it does for the published JSON Schemas.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from opseval.server import schemas

OUT = Path(__file__).resolve().parent.parent / "packages" / "console" / "src" / "lib" / "api.gen.ts"
HEADER = (
    "// GENERATED by scripts/console_types.py from opseval.server.schemas. Do not edit:\n"
    "// change the Python model and run `uv run python scripts/console_types.py`.\n"
    '// null is "not measured" and is never drawn as 0 (ADR-0029).\n'
)


def models() -> list[type[BaseModel]]:
    """Every request and response model, in the order the module defines them."""
    bases = (schemas.Api, schemas.ApiIn)
    return [
        obj
        for obj in vars(schemas).values()
        if isinstance(obj, type) and issubclass(obj, bases) and obj not in bases
    ]


def ts(node: dict[str, Any]) -> str:
    """The TypeScript type for one JSON Schema node."""
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    if "anyOf" in node:
        parts = list(dict.fromkeys(ts(n) for n in node["anyOf"]))
        return " | ".join(parts)
    kind = node.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = ts(node.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object":
        extra = node.get("additionalProperties")
        value = ts(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def interface(model: type[BaseModel]) -> str:
    request = issubclass(model, schemas.ApiIn)
    schema = model.model_json_schema(
        by_alias=True, mode="validation" if request else "serialization"
    )
    required = set(schema.get("required", []))
    doc = (model.__doc__ or "").strip().splitlines()
    lines = [f"/** {doc[0]} */"] if doc and doc[0] else []
    lines.append(f"export interface {model.__name__} {{")
    for name, prop in schema.get("properties", {}).items():
        # A response always carries every field; a request may leave out what has a default.
        optional = request and name not in required
        lines.append(f"  {name}{'?' if optional else ''}: {ts(prop)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    return HEADER + "\n" + "\n\n".join(interface(m) for m in models()) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text("utf-8") != text:
            print(f"{OUT} is out of date: run `uv run python scripts/console_types.py`")
            return 1
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
