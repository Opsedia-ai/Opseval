"""Generate the docs site's reference pages from the code.

    uv run python scripts/reference_docs.py          # write docs/reference/{scorers,settings}.md
    uv run python scripts/reference_docs.py --check  # fail if they are out of date (make check)

A reference written by hand drifts: a scorer added, a setting renamed, a default changed, and
the page that people trust is wrong. These pages are generated from the scorer registry and from
``config.Settings`` (its field docstrings), and ``make check`` fails when they disagree, as it does
for the JSON Schemas and the console's types.
"""

from __future__ import annotations

import sys
import types
import typing
from pathlib import Path
from typing import Any

from opseval.config import SECRET_FIELDS, Settings
from opseval.scoring import INVARIANTS, REGISTRY

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
HEADER = (
    "<!-- GENERATED by scripts/reference_docs.py. Do not edit: change the code and run "
    "`uv run python scripts/reference_docs.py`. -->\n\n"
)
AXIS_ORDER = ("output", "flow", "tools", "conversation", "security", "protocol", "harness")


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def scorers() -> str:
    by_axis: dict[str, list[Any]] = {}
    for sid, cls in sorted(REGISTRY.items()):
        by_axis.setdefault(cls.axis.value, []).append((sid, cls))
    order = [a for a in AXIS_ORDER if a in by_axis] + sorted(set(by_axis) - set(AXIS_ORDER))
    lines = [
        "# Scorer reference",
        "",
        "Every built-in scorer, by the axis it grades. *Needs* is the evidence it requires:",
        "`frames` (the recorded conversation), `trace` (the agent's tool calls from a trace",
        "source) or `llm` (a judge model). A scorer whose evidence is missing reports",
        "*not measured*, never a pass or a fail. The `harness` axis grades Opseval's own",
        "simulator: a failure there makes the attempt *not judged*, never an agent failure.",
        "",
        "Name a scorer in a scenario's `scorers:` list, for example",
        "`{id: judge.goal_achievement, threshold: 0.8}`.",
    ]
    for axis in order:
        lines += ["", f"## {axis}", "", "| Scorer | Needs | Version | What it checks |"]
        lines.append("|---|---|---|---|")
        for sid, cls in by_axis[axis]:
            lines.append(f"| `{sid}` | {cls.requires} | {cls.version} | {_cell(cls.description)} |")
    lines += [
        "",
        "## Invariant bundles",
        "",
        "`expectations.invariants` names a bundle; each adds the scorer it maps to.",
        "",
        "| Invariant | Scorer |",
        "|---|---|",
        *(f"| `{name}` | `{sid}` |" for name, sid in sorted(INVARIANTS.items())),
    ]
    return HEADER + "\n".join(lines) + "\n"


def _type(annotation: Any) -> str:
    if isinstance(annotation, types.UnionType) or typing.get_origin(annotation) is typing.Union:
        parts = [_type(a) for a in typing.get_args(annotation) if a is not type(None)]
        return " or ".join(parts)
    if typing.get_origin(annotation) is typing.Literal:
        return " \\| ".join(f"`{v}`" for v in typing.get_args(annotation))
    name = getattr(annotation, "__name__", str(annotation))
    return {"SecretStr": "secret", "str": "text", "int": "integer", "float": "number"}.get(
        name, name
    )


def _env(name: str, field: Any) -> str:
    alias = field.validation_alias
    choices = getattr(alias, "choices", None)
    if choices:
        return " or ".join(f"`{c}`" for c in choices)
    return f"`OPSEVAL_{name.upper()}`"


def settings() -> str:
    lines = [
        "# Settings reference",
        "",
        "Every setting is an environment variable (or a line in `.env`). Nothing else reads the",
        "environment. Secrets are redacted in every output, including the config digest stored",
        "with each run. Any host that receives a conversation or a key must also be listed in",
        "`OPSEVAL_ALLOWED_HOSTS`.",
        "",
        "| Variable | Type | Default | What it does |",
        "|---|---|---|---|",
    ]
    for name, field in Settings.model_fields.items():
        if name in SECRET_FIELDS:
            default = "unset (secret)"
        elif field.default is None:
            default = "unset"
        elif field.default == "":
            default = "empty"
        else:
            default = f"`{field.default}`"
        lines.append(
            f"| {_env(name, field)} | {_type(field.annotation)} | {default} | "
            f"{_cell(field.description or '')} |"
        )
    return HEADER + "\n".join(lines) + "\n"


PAGES = {"scorers.md": scorers, "settings.md": settings}


def main(argv: list[str]) -> int:
    stale = []
    for name, render in PAGES.items():
        path, text = OUT / name, render()
        if "--check" in argv:
            if not path.is_file() or path.read_text("utf-8") != text:
                stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, "utf-8")
        print(f"wrote {path}")
    for path in stale:
        print(f"{path} is out of date: run `uv run python scripts/reference_docs.py`")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
